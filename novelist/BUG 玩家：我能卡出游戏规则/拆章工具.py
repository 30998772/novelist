def han(t):
    return len(re.findall(r'[\u4e00-\u9fff]', t))


def split_points(paras):
    cands, anyc, acc = [], [], 0
    for i, p in enumerate(paras):
        acc += han(p)
        if i == 0 or i == len(paras) - 1 or not p.strip():
            continue
        if not (LO <= acc <= HI):
            continue
        s = p.strip()
        prev = paras[i - 1].strip()
        is_narr = not s.startswith(('"', '“', '「', '`', '【', '>', '-'))
        prev_dlg = prev.startswith(('"', '“', '「', '`', '【', '>'))
        anyc.append((i, acc, 1))
        if is_narr and prev_dlg:
            cands.append((i, acc, 3))
    return cands, anyc


