def process():
    if os.path.isdir(DST):
        shutil.rmtree(DST)
    st = {'in': 0, 'out': 0, 'split': 0, 'kept': 0}
    n = 0
    all_used = set()
    for part in ['第一部', '第二部', '第三部', '第四部']:
        os.makedirs(f'{DST}/{part}', exist_ok=True)
        for path in sorted(glob.glob(f'{SRC}/{part}/*.md')):
            st['in'] += 1
            base = os.path.basename(path)
            orig = base.split('-', 1)[1][:-3]
            orig_num = int(base[1:4])
            paras = [p for p in open(path, encoding='utf-8').read().split('\n\n') if p.strip()]
            body = paras[1:]

            cands, anyc = split_points(body)
            total = han(''.join(body))
            half = total / 2.0

            def score(x):
                # 越接近对半分越好，其次接近目标
                return abs(x[1] - half) * 2.0 + abs(x[1] - TARGET) * 0.3 - x[2]

            cut = None
            pool = cands if cands else anyc
            if pool:
                cut = min(pool, key=score)[0]

            if cut is None:
                n += 1; st['kept'] += 1; st['out'] += 1
                all_used.add(orig)
                open(f'{DST}/{part}/第{n:03d}章-{orig}.md', 'w', encoding='utf-8') \
                    .write('\n\n'.join([f'# 第{n:03d}章 {orig}'] + body))
                continue

            st['split'] += 1
            a, b = body[:cut], body[cut:]
            used = all_used | {orig}

            n += 1
            t1 = orig + '（上）'
            all_used.add(t1)
            open(f'{DST}/{part}/第{n:03d}章-{t1}.md', 'w', encoding='utf-8') \
                .write('\n\n'.join([f'# 第{n:03d}章 {t1}'] + a))

            n += 1
            t2 = SECOND_HALF_TITLE.get(orig_num, orig + '（下）')
            all_used.add(t2)
            open(f'{DST}/{part}/第{n:03d}章-{t2}.md', 'w', encoding='utf-8') \
                .write('\n\n'.join([f'# 第{n:03d}章 {t2}'] + b))
            st['out'] += 2
    return st


if __name__ == '__main__':
    s = process()
    print(f"原 {s['in']} 章 → 拆后 {s['out']} 章（拆开 {s['split']}，未拆 {s['kept']}）")
