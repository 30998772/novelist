    src = os.path.join(d, "第%s章-%s.md" % (num, old))
    dst = os.path.join(d, "第%s章-%s.md" % (num, new))
    if not os.path.exists(src):
        print("MISSING", src); continue
    with io.open(src, encoding="utf-8") as f:
        c = f.read()
    oldh = "# 第%s章 %s" % (num, old)
    newh = "# 第%s章 %s" % (num, new)
    if not c.startswith(oldh):
        print("HEADER-MISMATCH", num, repr(c.split("\n")[0])); continue
    c = newh + c[len(oldh):]
    with io.open(dst,"w",encoding="utf-8") as f:
        f.write(c)
    if dst != src:
        os.remove(src)
    print("OK", num, old, "->", new)
