f = '章节大纲/第六部/逐章卡片.md'
t = open(f, encoding='utf-8').read()
blocks = re.split(r'(?m)^(?=### 第\d+章)', t)
head = blocks[0]
by = {}
for b in blocks[1:]:
    m = re.match(r'### 第\d+章[：:]\s*(.+?)\n', b)
    if m:
        by.setdefault(m.group(1).strip(), b)

c = [(int(re.match(r'第(\d+)章', os.path.basename(x)).group(1)),
      os.path.basename(x).split('-', 1)[1][:-3]) for x in sorted(glob.glob('%s/*.md' % d))]

out = []
for i, title in c:
    if i in CARDS:
        ti, scene, goal, event, hook = CARDS[i]
        b = ('### 第%d章：%s\n- **场景**：%s\n- **本章目标**：%s\n'
             '- **事件**：%s\n- **钩子**：%s\n\n' % (i, title, scene, goal, event, hook))
    else:
        b = by.get(title)
        if b is None:
            print('STILL MISSING', i, title)
            continue
        b = re.sub(r'(?m)^### 第\d+章[：:].*$', '### 第%d章：%s' % (i, title), b, count=1)
    out.append(b.rstrip() + '\n\n')

open(f, 'w', encoding='utf-8').write(head + ''.join(out))
