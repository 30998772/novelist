import re

f = '正文/第四部/第001章-修缮的开始.md'
t = open(f, encoding='utf-8').read()

fixes = [
 # 清晨 —— 套话
 ('天空还带着一层薄薄的灰蓝色，像没有睡醒的样子。', '天空是灰蓝色的，太阳还没上来。'),
 # 墙皮开裂 —— 比喻多余，句子本身说清了
 ('有的地方墙皮已经开裂，像老人脸上的皱纹，', '有的地方墙皮已经开裂，翘起来一片一片，'),
 # 青苔 —— 青苔干透了不像绒布
 ('瓦面上覆着一层细密的青苔，干透了，像一小片绒布。', '瓦面上覆着一层细密的青苔，干透了，一碰就掉粉。'),
 # 石子投湖 —— 烂俗
 ('他的声音不大，但很清晰，像一颗石子投入了平静的湖面。', '他的声音不大，院子里每个人都听见了。'),
 # 这章讲的就是精灵，灰尘变成精灵是荒唐的
 ('灰尘在阳光中飞舞，像无数微小的精灵在跳舞。', '灰尘在阳光里飞舞，一层一层地浮。'),
 # 和全书记忆点「像是在回应她」重复
 ('建筑之灵微微震动了一下，像是在回应她。', '建筑之灵微微震动了一下。'),
 # 老朋友 —— 这本书后文会真的写老朋友，这里提前用掉
 ('她的动作很慢，很仔细，像是在和一个老朋友交谈。', '她的动作很慢，很仔细。'),
 # 同章内两次「种子埋进土里」
 ('它太微弱了，像一粒种子在泥土里沉睡。', '它太微弱了，若有若无。'),
 ('黑暗中，那本书静悄悄地躺着，像一粒种在泥里的种子，', '黑暗中，那本书静悄悄地躺着，'),
 # 一年两次「一把巨大的伞」，且无信息
 ('树冠像一把巨大的伞。', '树冠压得很低。'),
 ('它站在那里，像是大地的守护者，', '它站在那里，'),
 # 老人脸上的皱纹又出现
 ('心里那点不安，像被瓦片压住的一角，', '心里那点不安，被瓦片压着，'),
]

for a, b in fixes:
    if a not in t:
        print('MISS', repr(a[:26]))
    t = t.replace(a, b, 1)

t = re.sub(r'\n{3,}', '\n\n', t)
open(f, 'w', encoding='utf-8').write(t)
print('比喻', len(re.findall(r'像[^，。！？]{2,14}', t)),
      '字数', len(re.findall(r'[\u4e00-\u9fff]', t)))
