import re, glob

# 「不是用耳朵，是用心」是全书的中心母题，但第三部把它说了 12 次。
# Keep it where it lands (the ear-deaf musician's own line, twice).
# Everywhere else, state it plainly.
CUTS = {
 '正文/第三部/第004章-精灵的独白.md': [
   ('等他真正听见了——不是用耳朵，是用心——他就会知道那个结尾是什么。',
    '等他真正听见了，他就会知道那个结尾是什么。'),
 ],
 '正文/第三部/第005章-林越的困惑.md': [
   ('不是用眼睛看，不是用耳朵听，是用心。', '用眼睛看和用耳朵听都不够。'),
 ],
 '正文/第三部/第012章-精灵的感动.md': [
   ('不是用耳朵，而是用一种更深的感知。', '那道感知比耳朵深。'),
   ('不是用耳朵听见，而是用心听见。', '他听见了。'),
 ],
 '正文/第三部/第021章-音乐的回声.md': [
   ('他学会了在演奏的时候"听"——不是用耳朵听，而是用心听。',
    '他学会了在演奏的时候"听"。'),
 ],
 '正文/第三部/第042章-周明远的音乐会.md': [
   ('他的音乐不是用耳朵听的，是用心感受的。', '他弹的时候，整个人在动。'),
   ('他只想说一件事——音乐是用心听的，不是用耳朵听的。',
    '"弹的时候我知道谁在听。"'),
 ],
}

for f, subs in CUTS.items():
    t = open(f, encoding='utf-8').read()
    for a, b in subs:
        if a not in t:
            print('MISS', f.split('/')[-1][:16], repr(a[:26]))
        t = t.replace(a, b, 1)
    t = re.sub(r'\n{3,}', '\n\n', t)
    open(f, 'w', encoding='utf-8').write(t)
print('done')
