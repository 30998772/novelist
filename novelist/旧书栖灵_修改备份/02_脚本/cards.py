import re

f = '章节大纲/第一部/逐章卡片.md'
t = open(f, encoding='utf-8').read()

# 1) split card 030 into 030 + 031
old30 = """### 第030章 执念终有归处
- **场景**：文献馆，雪夜
- **本章目标**：雪夜茶话会
- **事件**：无题诗裱起来上墙；馆务交棒
- **钩子**：裱框悬挂的无题诗
"""
new30 = """### 第030章 执念终有归处
- **场景**：文献馆，雪夜
- **本章目标**：雪夜茶话会，诸灵各述所等
- **事件**：阿棠那四句诗被读出；散会时雪停
- **钩子**：顾松年把陆栖单独留下

### 第031章 交灯
- **场景**：文献馆，办公室
- **本章目标**：馆务交棒
- **事件**：转正批文下发；顾松年交代留灯的规矩
- **钩子**：二楼那盏灯交到陆栖手上
"""
assert old30 in t
t = t.replace(old30, new30)

# 2) renumber 031..060 -> 032..061
for n in range(60, 30, -1):
    pat = '### 第%03d章 ' % n
    if pat in t:
        t = t.replace(pat, '### 第%03d章 ' % (n + 1), 1)

# 3) fix the volume headers
t = t.replace('## 卷五：执念与释然（025-030）', '## 卷五：执念与释然（025-030）')
t = t.replace('## 卷六：旧书常明（031-036）', '## 卷六：旧书常明（032-037）')
for old, new in [('037-042', '038-043'), ('043-048', '044-049'),
                 ('049-054', '050-055'), ('055-060', '056-061')]:
    t = t.replace('（%s）' % old, '（%s）' % new)

open(f, 'w', encoding='utf-8').write(t)
print('cards updated')
