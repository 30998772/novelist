#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""第三部：人工逐条核验通过的 陆栖→「他」 错误 定点修正（第二批）"""
import os

DIR = '/mnt/d/devProject/writer/novelist/旧书栖灵/正文/第三部'

FIXES = [
    # ---- A类：男性主语 + 宾语位「他」，受事为陆栖 ----
    ('第005章-林越的困惑.md',
     '林越转过头，看了他一眼，笑了一下：',
     '林越转过头，看了她一眼，笑了一下：',
     '林越看向提问的陆栖'),
    ('第005章-林越的困惑.md',
     '林越转过头，端详着他。',
     '林越转过头，端详着她。',
     '陆栖刚说完话，林越端详她'),
    ('第005章-林越的困惑.md',
     '林越把竹笛递给他。陆栖拿在手里看了看',
     '林越把竹笛递给她。陆栖拿在手里看了看',
     '下一句主语即陆栖，竹笛递给她'),
    ('第007章-第一乐章.md',
     '周明远转过头，瞅着他，微微一怔，然后笑了。',
     '周明远转过头，瞅着她，微微一怔，然后笑了。',
     '上句陆栖说话，周明远看向她'),
    # ---- B类：对话标签「他说/他问」，说话人为陆栖 ----
    ('第005章-林越的困惑.md',
     '"算。"他说。',
     '"算。"她说。',
     '陆栖回答林越'),
    ('第007章-第一乐章.md',
     '"周先生，"他说，"你愿不愿意，先在庭院里演奏一次？"',
     '"周先生，"她说，"你愿不愿意，先在庭院里演奏一次？"',
     '陆栖向周明远提议'),
    ('第007章-第一乐章.md',
     '"周先生，"他说，"这只是开始。"',
     '"周先生，"她说，"这只是开始。"',
     '上段「陆栖站起来，走到周明远身边」，说话人陆栖'),
    ('第009章-苏晚晴的回忆.md',
     '"后来呢？"他问。',
     '"后来呢？"她问。',
     '上段「陆栖听着……一模一样的话」，提问者陆栖'),
    ('第009章-苏晚晴的回忆.md',
     '"谢谢你，苏老师。"他说。',
     '"谢谢你，苏老师。"她说。',
     '上段「陆栖接过信封」，陆栖致谢'),
    ('第010章-林越的音乐.md',
     '"周维德写的那首？"他问。',
     '"周维德写的那首？"她问。',
     '上段「陆栖微微一怔」，发问者陆栖'),
]

total = 0
files = set()
for fn, old, new, why in FIXES:
    p = os.path.join(DIR, fn)
    s = open(p, encoding='utf-8').read()
    n = s.count(old)
    if n != 1:
        print('!! 跳过(匹配%d次) %s :: %s' % (n, fn, old[:28]))
        continue
    open(p, 'w', encoding='utf-8').write(s.replace(old, new, 1))
    total += 1
    files.add(fn)
    print('OK  [%s] %s' % (why, old[:36]))
print('---')
print('本批替换:', total, '涉及文件:', len(files), sorted(files))
