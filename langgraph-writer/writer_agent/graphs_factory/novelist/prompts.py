# ════════════════════════════════════════════════════════════════
# 意图识别 JSON Schema（Pydantic model）
# ════════════════════════════════════════════════════════════════

from pydantic import BaseModel, Field


class IntentOutput(BaseModel):
    """意图识别输出结构。"""
    intents: list[str] = Field(
        default_factory=list,
        description="识别到的意图列表，按执行顺序排列。可选值：构思、设计、创作、审稿、修改、评估、包装",
    )

