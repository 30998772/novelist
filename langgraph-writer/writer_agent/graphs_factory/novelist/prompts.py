# ════════════════════════════════════════════════════════════════
# 计划 JSON Schema（Pydantic model）
# ════════════════════════════════════════════════════════════════

from pydantic import BaseModel, Field


class PlanStep(BaseModel):
    """计划中的一步：调用哪个子图，让它做什么。"""

    intent: str = Field(
        description="本步要调用的子图名称。可选值：构思、设计、创作、审稿、修改、评估、包装",
    )
    task: str = Field(
        default="",
        description="本步的具体任务要求，直接透传给对应子图",
    )


class PlanOutput(BaseModel):
    """计划输出结构：按执行顺序排列的步骤列表。"""

    plan: list[PlanStep] = Field(
        default_factory=list,
        description="按执行顺序排列的创作计划步骤",
    )

